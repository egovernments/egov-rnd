    def processJSON(self, json_object, append_string=""):
        # This converts the json object returned from ES search to a list of fields in that object, without losing the information of it's location. So that something at ["Data"]["tenantData"]["city"]["name"] will be converted to "Data.tenantData.city.name". Assumes it starts at Data.
        for k in json_object:
            if k=="type":
                self.index_dict[append_string] = json_object[k]
                return
            elif k=="fields":
                return
            elif k=="Data":
                return self.processJSON(json_object[k], self.es_index)
            elif k=="properties":
                for k in json_object:
                    self.processJSON(json_object[k], append_string)
                return
            else:
                for k in json_object:
                    self.processJSON(json_object[k], append_string+"."+k)
                return

    def getListOfColumns(self):
        # Collect ES credentials, attempt to fetch records, set the related drop-down lists to have these columns
        es_server = self.dlg.lineEdit.text()
        es_user = self.dlg.lineEdit_2.text()
        es_pass = self.dlg.lineEdit_3.text()
        es_index = self.dlg.lineEdit_4.text()
        self.es_index = es_index
        try:
            self.es_client = Elasticsearch(
                hosts = es_server,
                basic_auth=(es_user, es_pass),
                ca_certs=False,
                verify_certs=False,
                headers={"Accept": "application/json", "Content-Type": "application/json"}
            )
            self.index_dict = {}
            self.processJSON(self.es_client.indices.get_mapping(index=es_index))

            for row_c in range(1, self.dlg.tableWidget.rowCount()+1):
                if self.dlg.tableWidget.cellWidget(row_c-1, 1).currentText() == "Index":
                    column_picker = self.dlg.tableWidget.cellWidget(row_c-1, 2)
                    cT = column_picker.currentText()
                    column_picker.clear()
                    for k in self.index_dict:
                        column_picker.addItem(k, k)
                    if column_picker.findText(cT) >= 0:
                        column_picker.setCurrentIndex(column_picker.findText(cT))
                    self.changeConditionPicker(column_picker.currentText(), row_c-1)
            return self.es_client.info()
        except Exception:
            QMessageBox.information(None, "ERROR:", str(traceback.format_exc())) 
            self.iface.messageBar().pushInfo(__name__, str(traceback.format_exc()))

    def getListOfAttributes(self):
        # Collect layer on the current project by name, go through its attributes and make a list of them prepended with the shapefile name.
        try:
            current_layer = self.shapefile_picker.currentLayer()
            layer_name = current_layer.name()
            for f in current_layer.fields():
                if f.type() in [1]:
                    self.shapefile_dict[layer_name+"."+f.name()] = "boolean"
                elif f.type() in [2, 3, 32, 4, 5, 36, 33]:
                    self.shapefile_dict[layer_name+"."+f.name()] = "long"
                elif f.type() in [6, 38, 63]:
                    self.shapefile_dict[layer_name+"."+f.name()] = "float"
                elif f.type() in [7, 10 , 12, 34, 56, 57, 40, 37]:
                    self.shapefile_dict[layer_name+"."+f.name()] = "text"
                elif f.type() in [14, 15, 16]:
                    self.shapefile_dict[layer_name+"."+f.name()] = "date"
            for row_c in range(1, self.dlg.tableWidget.rowCount()+1):
                if self.dlg.tableWidget.cellWidget(row_c-1, 1).currentText() == "Shapefile":
                    column_picker = self.dlg.tableWidget.cellWidget(row_c-1, 2)
                    cT = column_picker.currentText()
                    column_picker.clear()
                    for k in self.shapefile_dict:
                        column_picker.addItem(k, k)
                    if column_picker.findText(cT) >= 0:
                        column_picker.setCurrentIndex(column_picker.findText(cT))
                    self.changeConditionPicker(column_picker.currentText(), row_c-1)
            self.active_layers.append(current_layer)
            self.shapefile_picker.setExceptedLayerList(self.active_layers)
        except Exception:
            QMessageBox.information(None, "ERROR:", str(traceback.format_exc())) 
            self.iface.messageBar().pushInfo(__name__, str(traceback.format_exc()))

    def changeColumnPicker(self, text, index):
        # Depending on if the type of data source is an index or shapefile, sets up the dropdown up for conditions for that row
        column_picker = QComboBox()
        column_picker.currentTextChanged.connect(lambda text, index=index: self.changeConditionPicker(text, index))
        if text == "Index":
            for k in self.index_dict:
                column_picker.addItem(k, k)
            if len(list(self.index_dict.keys())) > 0:
                self.changeConditionPicker(list(self.index_dict.keys())[0], index)
            else:
                self.changeConditionPicker("", index)
        elif text == "Shapefile":
            for k in self.shapefile_dict:
                column_picker.addItem(k, k)
            if len(list(self.shapefile_dict.keys())) > 0:
                self.changeConditionPicker(list(self.shapefile_dict.keys())[0], index)
            else:
                self.changeConditionPicker("", index)
        else:
            self.changeConditionPicker("", index)
        self.dlg.tableWidget.setCellWidget(index, 2, column_picker)

    def changeConditionPicker(self, text, index):
        # Depending on the type of the field selected in the corresponding column picker, set this dropdown to have a set of options that can be applied on that type of field.
        condition_picker = QComboBox()
        use_dict = {}
        type = self.dlg.tableWidget.cellWidget(index, 1).currentText()
        if type=="":
            pass
        elif type=="Index":
            use_dict = self.index_dict
        elif type=="Shapefile":
            use_dict = self.shapefile_dict
        if text not in use_dict:
            pass
        elif use_dict[text]=="text":
            condition_picker.addItem("matches", "matches")
            condition_picker.addItem("reverse in", "reverse in")
            condition_picker.addItem("regex", "regex")
        elif use_dict[text]=="long" or use_dict[text]=="float":
            condition_picker.addItem("==", "==")
            condition_picker.addItem(">=", ">=")
            condition_picker.addItem(">", ">")
            condition_picker.addItem("<=", "<=")
            condition_picker.addItem("<", "<")
        elif use_dict[text]=="boolean":
            condition_picker.addItem("is", "is")
        elif use_dict[text]=="date":
            condition_picker.addItem("on", "on")
            condition_picker.addItem("on or before", "on or before")
            condition_picker.addItem("on or after", "on or after")
            condition_picker.addItem("before", "before")
            condition_picker.addItem("after", "after")
        else:
            self.iface.messageBar().pushInfo(__name__, str(use_dict[text]))
        self.dlg.tableWidget.setCellWidget(index, 3, condition_picker)
        
