    def translateToES(self, feature, condition, value):
        # Translate the rules parsed using the rule texts into a query string suitable for an ES query
        match condition:
            case "matches":
                return feature+".keyword:"+value
            case "reverse in" | "is":
                return feature+":\\\""+value+"\\\""
            case "regex":
                return feature+":/"+value+"/"
            case "on" | "==":
                return feature+":"+value
            case "or or before" | "<=":
                return feature+":<="+value
            case "or or after" | ">=":
                return feature+":>="+value
            case "before" | "<":
                return feature+":<"+value
            case "after" | ">":
                return feature+":>"+value
            
    def translateToExpression(self, feature, condition, value):
        # Translate the rules parsed using the rule texts into an expression that QGIS is able to select features by
        match condition:
            case "matches" | "on" | "==" | "is":
                return "\"" + feature + "\" = \'" + str(value) + "\'"
            case "reverse in":
                return "strpos(lower(\"" + feature + "\"), lower(\'" + str(value) +"\')) != 0"
            case "regex":
                return "regexp_match(lower(\"" + feature + "\"), lower(\'" + str(value) +"\')) != 0"
            case "or or before" | "<=":
                return "\"" + feature + "\" <= " + str(value)
            case "or or after" | ">=":
                return "\"" + feature + "\" >= " + str(value)
            case "before" | "<":
                return "\"" + feature + "\" < " + str(value)
            case "after" | ">":
                return "\"" + feature + "\" > " + str(value)
            
