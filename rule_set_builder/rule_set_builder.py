    def parseTable(self):
        # Construct a json that includes all the information involved in running the ruleset.
        # rules is not currently used, but it is designed in case we implement editing for older rulesets.
        # joins is a string that explains how the different data stores are joined, delimited by @
        # query is the ES query for indices, and the expression by which to select for shapefiles
        # types is a mapping of each data source to the kind of data source it is, index or shapefile
        # The rules are fetched piece by piece from all the rows
        output_json = {"rules": {}, "joins": "@", "query": {}, "types": {}}

        for i in range(1, self.dlg.tableWidget.rowCount()+1):
            query = "\""
            chosen_type = self.dlg.tableWidget.cellWidget(i-1, 1).currentData()
            if chosen_type == "":
                continue
            elif chosen_type=="Index": # For ES indices
                line = ""
                source, feature = self.dlg.tableWidget.cellWidget(i-1, 2).currentData().split(".", 1)
                if i != 1:
                    line += self.dlg.tableWidget.cellWidget(i-1, 0).currentData() + " "
                    query = self.dlg.tableWidget.cellWidget(i-1, 0).currentData() + " "
                if source not in output_json["rules"]:
                    output_json["rules"][source] = ""
                    output_json["query"][source] = ""
                    if line.strip():
                        output_json["joins"] += "$"+line.strip()+"$@" + source + "@" # The join will be as $AND$ or $OR$ 
                    else:
                        output_json["joins"] += source + "@"
                    output_json["types"][source] = "Index"
                    line = ""
                    query = ""
                line += self.dlg.tableWidget.cellWidget(i-1, 2).currentData() + " "
                line += self.dlg.tableWidget.cellWidget(i-1, 3).currentData() + " "
                line += self.dlg.tableWidget.item(i-1, 4).text() + " "
                query += "Data." + self.translateToES(feature, self.dlg.tableWidget.cellWidget(i-1, 3).currentData(), self.dlg.tableWidget.item(i-1, 4).text())+ " "
                output_json["rules"][source] += line
                output_json["query"][source] += query
            elif chosen_type=="Shapefile": # For shapefiles or map files
                line = ""
                source, feature = self.dlg.tableWidget.cellWidget(i-1, 2).currentData().split(".", 1)
                if i != 1:
                    line += self.dlg.tableWidget.cellWidget(i-1, 0).currentData() + " "
                    query = self.dlg.tableWidget.cellWidget(i-1, 0).currentData().lower() + " "
                if source not in output_json["rules"]:
                    output_json["rules"][source] = ""
                    output_json["query"][source] = ""
                    if line.strip():
                        output_json["joins"] += "$"+line.strip()+"$@" + source + "@" # The join will be as $AND$ or $OR$ 
                    else:
                        output_json["joins"] += source + "@"
                    output_json["types"][source] = "Shapefile"
                    line = ""
                    query = ""
                line += self.dlg.tableWidget.cellWidget(i-1, 2).currentData() + " "
                line += self.dlg.tableWidget.cellWidget(i-1, 3).currentData() + " "
                line += self.dlg.tableWidget.item(i-1, 4).text() + " "
                query += self.translateToExpression(feature, self.dlg.tableWidget.cellWidget(i-1, 3).currentData(), self.dlg.tableWidget.item(i-1, 4).text())+ " "
                output_json["rules"][source] += line
                output_json["query"][source] += query
        for k in output_json["query"]:
            if output_json["types"][k] == "Index":
                output_json["query"][k] = "{\"query\": {\"query_string\": {\"query\":\""+output_json["query"][k][:-1]+"\"}}}" # Query string format for ES queries
            elif output_json["types"][k] == "Shapefile":
                output_json["query"][k] = output_json["query"][k][:-1]
        for k in output_json['rules']:
            output_json["rules"][k] = output_json["rules"][k][:-1]
        output_json["joins"] = output_json["joins"].strip()[1:-1]
        return output_json

    def runQuery(self):
        # To decide where the queries are coming from, then to decide where the data is coming from, then to run the query on the data and generate maps and json outputs
        try:
            if self.dlg.radioButton.isChecked(): # If checked, fetch current ruleset, if not fetch the file and process it for the rules
                output_json = self.parseTable()
            else:
                filename = self.dlg.textEdit.toPlainText()
                with open(filename) as fp:
                    output_json = json.load(fp)
            function_flag = True
            if self.dlg.comboBox.currentText()=="Generate maps on historical data":
                function_flag = True
            elif self.dlg.comboBox.currentText()=="Classify a file of new properties":
                function_flag = False
            current_operation = "INITIAL"
            final_polygon_layer = None
            final_point_layer = None
            if function_flag: # Historical data
                if not self.es_client:
                    try:
                        es_server = self.dlg.lineEdit.text()
                        es_user = self.dlg.lineEdit_2.text()
                        es_pass = self.dlg.lineEdit_3.text()
                        self.es_client = Elasticsearch(
                            hosts = es_server,
                            basic_auth=(es_user, es_pass),
                            ca_certs=False,
                            verify_certs=False,
                            headers={"Accept": "application/json", "Content-Type": "application/json"}
                        )
                    except Exception:
                        QMessageBox.information(None, "ERROR:", str(traceback.format_exc())) 
                        self.iface.messageBar().pushInfo(__name__, str(traceback.format_exc()))
            indices = []
            shapefiles = []
            shapefile_operators = []
            sf = -1
            for itr in output_json["joins"].split("@"):
                if itr == "$AND$" or itr == "$OR$": # This is the join between adjacent data sources, defining how they will be joined. This doesn't matter if one of the sources is the index, as we will always take an intersection with the index
                    shapefile_operators.append(itr.strip("$"))
                else:
                    if output_json["types"][itr]=="Index":
                        indices.append(itr)
                        if sf == 1:
                            shapefile_operators = shapefile_operators[:-1] # Ignoring the index join
                    elif output_json["types"][itr]=="Shapefile":
                        shapefiles.append(itr)
                        sf = 1
            for ind in indices: # Process indices first
                if function_flag:
                    current_results = [x for x in scan(self.es_client, query = json.loads(output_json["query"][ind]), index=ind)] # ES search
                    self.iface.messageBar().pushInfo(__name__, str(json.loads(output_json["query"][ind])))
                else:
                    with open(self.dlg.textEdit_3.toPlainText()) as fp:
                        current_results = json.load(fp) # Load data in the same format as what ES returns on search
                    original_results = current_results
                    current_results = self.processQuery(current_results["hits"]["hits"], output_json["query"][ind])
                final_point_layer = self.createPointMap(current_results)
                final_polygon_layer = self.createAggregationMap(current_results)
            current_operation = "INITIAL"
            current_polygon_layer = None
            for shp in shapefiles: # Process all shapefiles, merging them based on the rules before finding the final intersection
                select_layer = QgsProject.instance().mapLayersByName(shp)[0]
                select_layer.selectByExpression(output_json["query"][shp])
                new_polygon_layer = processing.run("native:saveselectedfeatures", {'INPUT': select_layer, 'OUTPUT': 'memory:'})['OUTPUT']
                select_layer.removeSelection()
                if current_operation == "AND":
                    current_polygon_layer = processing.run("qgis:intersection", {'INPUT': current_polygon_layer, 'OVERLAY': new_polygon_layer, 'OUTPUT': 'memory:'})['OUTPUT']
                elif current_operation == "OR":
                    current_polygon_layer = processing.run("qgis:union", {'INPUT': current_polygon_layer, 'OVERLAY': new_polygon_layer, 'OUTPUT': 'memory:'})['OUTPUT']
                elif current_operation == "INITIAL":
                    current_polygon_layer = new_polygon_layer
                if len(shapefile_operators) > 0:
                    current_operation = shapefile_operators[0]
                    shapefile_operators = shapefile_operators[1:]
            if current_polygon_layer: # Final intersection of index and shapefile maps
                params = {
                    'INPUT': final_polygon_layer,
                    'PREDICATE': [0],  # 0 = intersects
                    'INTERSECT': current_polygon_layer,
                    'METHOD': 0  # 0 = create new selection, 1 = add to current, 2 = remove from current
                }
                processing.run("native:selectbylocation", params)
                new_layer = processing.run("native:saveselectedfeatures", {'INPUT': final_polygon_layer, 'OUTPUT': 'memory:'})['OUTPUT']
                final_polygon_layer.removeSelection()
                final_polygon_layer = new_layer
                if final_point_layer:
                    params = {
                        'INPUT': final_point_layer,
                        'PREDICATE': [0],  # 0 = intersects
                        'INTERSECT': current_polygon_layer,
                        'METHOD': 0  # 0 = create new selection, 1 = add to current, 2 = remove from current
                    }
                    processing.run("native:selectbylocation", params)
                    new_layer = processing.run("native:saveselectedfeatures", {'INPUT': final_point_layer, 'OUTPUT': 'memory:'})['OUTPUT']
                    final_point_layer.removeSelection()
                    final_point_layer = new_layer
            field_name = 'aggregateCount' # Setting the style so that the aggregation map is shown as a classified map with colors based on the counts in this field
            field_index = final_polygon_layer.fields().indexFromName(field_name)
            unique_values = final_polygon_layer.uniqueValues(field_index)
            category_list = []
            for value in unique_values:
                symbol = QgsSymbol.defaultSymbol(final_polygon_layer.geometryType())
                category = QgsRendererCategory(value, symbol, str(value))
                category_list.append(category)
            categorized_renderer = QgsCategorizedSymbolRenderer(field_name, category_list)
            categorized_renderer.setClassAttribute("aggregateCount")
            categorized_renderer.updateColorRamp(QgsStyle.defaultStyle().colorRamp("Viridis"))
            final_polygon_layer.setRenderer(categorized_renderer)

            QgsProject.instance().addMapLayer(final_polygon_layer) # Add maps to the current project, save to locations if those paths are provided
            if final_point_layer:
                QgsProject.instance().addMapLayer(final_point_layer)
            output_file_name = self.dlg.textEdit_5.toPlainText().strip()
            if output_file_name:
                QgsVectorFileWriter.writeAsVectorFormat(final_polygon_layer, output_file_name, "UTF-8", final_polygon_layer.crs(), "ESRI Shapefile") # "CP1250"
            output_file_name = self.dlg.textEdit_6.toPlainText().strip()
            if output_file_name and final_point_layer:
                QgsVectorFileWriter.writeAsVectorFormat(final_point_layer, output_file_name, "UTF-8", final_point_layer.crs(), "ESRI Shapefile") # "CP1250"
            output_file_name = self.dlg.textEdit_7.toPlainText().strip()
            if not function_flag and output_file_name:
                for itr in range(len(original_results["hits"]["hits"])):
                    classification = False
                    for f in final_point_layer.getFeatures():
                        if f["propertyId"] == original_results["hits"]["hits"][itr]["_source"]["Data"]["propertyId"]:
                            classification = True
                    original_results["hits"]["hits"][itr]["_classification"] = classification
                with open(output_file_name, "w") as fp:
                    json.dump(original_results, fp)
            QMessageBox.information(None, "COMPLETE", "Maps creation and optional classification complete")
        except Exception:
            QMessageBox.information(None, "ERROR:", str(traceback.format_exc())) 
            self.iface.messageBar().pushInfo(__name__, str(traceback.format_exc()))

    def processQuery(self, results, query):
        # Function called when running the query on new data, a parser built to replace the ES parser
        query = json.loads(query)["query"]["query_string"]["query"]
        query = query.split(" ")
        final_results = results
        current_results = final_results
        current_action = "AND"
        for q in query:
            if q=="AND":
                current_action = q
                current_results = final_results
            elif q=="OR":
                current_action = q
                current_results = results
            else:
                operation = None
                lhs, rhs = q.split(":", 1)
                call_order = lhs.split(".")
                attempt_convert = False
                if call_order[-1] == "keyword":
                    operation = lambda a, b: a==b
                elif rhs[:2]==">=":
                    operation = lambda a, b: a>=b
                    rhs = rhs[2:]
                    attempt_convert = True
                elif rhs[:1]==">":
                    operation = lambda a, b: a>b
                    rhs = rhs[1:]
                    attempt_convert = True
                elif rhs[:2]=="<=":
                    operation = lambda a, b: a<=b
                    rhs = rhs[2:]
                    attempt_convert = True
                elif rhs[:1]=="<":
                    operation = lambda a, b: a<b
                    rhs = rhs[1:]
                    attempt_convert = True
                elif rhs[:1]=="/":
                    operation = lambda a, b: re.search(b, a, flags=re.I)
                elif rhs[:2]=="\\\"":
                    operation = lambda a, b: b.strip("\"") in a
                else:
                    operation = lambda a, b: a==b
                    attempt_convert = True
                if attempt_convert:
                    try:
                        rhs = datetime.datetime.strptime(rhs, '%Y-%m-%dT%H:%M:%S.%fZ')
                    except Exception:
                        rhs = float(rhs)
                cfr = []
                for r in current_results:
                    cr = r["_source"]
                    for c in call_order:
                        cr = cr[c]
                    if attempt_convert:
                        try:
                            cr = datetime.datetime.strptime(cr, '%Y-%m-%dT%H:%M:%S.%fZ')
                        except Exception:
                            cr = float(cr)
                    if operation(cr, rhs):
                        cfr.append(r)
                if current_action=="AND":
                    final_results = cfr
                else:
                    ncfr = cfr
                    for r1 in cfr:
                        for r2 in final_results:
                            if r1["_id"]!=r2["_id"]:
                                ncfr.append(r2)
                    final_results = ncfr
        return final_results

    def createPointMap(self, result):
        # To generate the point map for the results of the ES search. This assumes the records have geographic coordinate information
        try:
            point_layer = QgsVectorLayer("Point?crs=EPSG:4326", "__points", "memory")
            point_layer.startEditing()
            provider = point_layer.dataProvider()
            provider.addAttributes([ # The fields currently in use, which this will replicate to the map's attribute table
                QgsField("propertyId", QVariant.String),
                QgsField("name", QVariant.String),
                QgsField("area",  QVariant.Double),
                QgsField("pincode", QVariant.LongLong),
                QgsField("noOfFloors", QVariant.Int),
                QgsField("usageCategory", QVariant.String),
                QgsField("propertyType", QVariant.String),
                QgsField("ownershipCategory", QVariant.String),
            ])
            point_layer.updateFields()
            for r in result:
                f = QgsFeature() # Assumptions have been made as to where in the index all the required data is
                f.setGeometry(QgsGeometry.fromPointXY(QgsPointXY(r["_source"]["Data"]["tenantData"]["city"]["longitude"], r["_source"]["Data"]["tenantData"]["city"]["latitude"])))
                f.setAttributes([r["_source"]["Data"]["propertyId"], r["_source"]["Data"]["tenantData"]["city"]["name"], r["_source"]["Data"]["landArea"], r["_source"]["Data"]["tenantData"]["pincode"][0], r["_source"]["Data"]["noOfFloors"], r["_source"]["Data"]["usageCategory"], r["_source"]["Data"]["propertyType"], r["_source"]["Data"]["ownershipCategory"]])
                point_layer.addFeature(f)
            point_layer.commitChanges()
            point_layer.updateExtents()
            background = self.background_layer_picker.currentLayer()
            params = {
                'INPUT': point_layer,
                'PREDICATE': [0],  # 0 = intersects
                'INTERSECT': background,
                'METHOD': 0  # 0 = create new selection, 1 = add to current, 2 = remove from current
            }
            processing.run("native:selectbylocation", params)
            final_layer = processing.run("native:saveselectedfeatures", {'INPUT': point_layer, 'OUTPUT': 'memory:'})['OUTPUT']
            point_layer.removeSelection()
            return final_layer
        except Exception:
            QMessageBox.information(None, "ERROR:", str(traceback.format_exc())) 
            self.iface.messageBar().pushInfo(__name__, str(traceback.format_exc()))

    def createAggregationMap(self, result):
        # This generates the aggregation map, aggregating to a postcode zone all the records that have it's pincode. Assumes that pincode exists for the records, which is generally true. Pincode map is saved within the plugin and to be shipped with it.
        try:
            plugin_dir = os.path.dirname(os.path.abspath(__file__))
            pincode_map = QgsVectorLayer(plugin_dir+"/pincode-map/pincode-map.shp", "pincode_map", "ogr")
            pincode_map.selectAll()
            output_layer = processing.run("native:saveselectedfeatures", {'INPUT': pincode_map, 'OUTPUT': 'memory:'})['OUTPUT']
            pincode_map.removeSelection()
            layer_provider=output_layer.dataProvider()
            layer_provider.addAttributes([QgsField("aggregateCount", QVariant.LongLong)])
            output_layer.updateFields()
            pincode_dict = {}
            for r in result:
                if r["_source"]["Data"]["tenantData"]["pincode"]!=[""]:
                    for pc in r["_source"]["Data"]["tenantData"]["pincode"]:
                        if int(pc) not in pincode_dict:
                            pincode_dict[int(pc)] = 0.0
                        pincode_dict[int(pc)] += 1
            output_layer.startEditing()
            for of in output_layer.getFeatures():
                if int(of["Pincode"]) not in pincode_dict:
                    pincode_dict[int(of["Pincode"])] = 0.0
                of["aggregateCount"] = pincode_dict[int(of["Pincode"])]
                output_layer.updateFeature(of)
            output_layer.commitChanges()
            background = self.background_layer_picker.currentLayer()
            params = {
                'INPUT': output_layer,
                'PREDICATE': [0],  # 0 = intersects
                'INTERSECT': background,
                'METHOD': 0  # 0 = create new selection, 1 = add to current, 2 = remove from current
            }
            processing.run("native:selectbylocation", params)
            final_layer = processing.run("native:saveselectedfeatures", {'INPUT': output_layer, 'OUTPUT': 'memory:'})['OUTPUT']
            output_layer.removeSelection()
            return final_layer
        except Exception:
            QMessageBox.information(None, "ERROR:", str(traceback.format_exc())) 
            self.iface.messageBar().pushInfo(__name__, str(traceback.format_exc()))


